// Browser validation for the explicit NPC+ promotion (dev only, offline). Needs `npm run build` and Playwright (see scripts/lib/browser-env.mjs). Screenshots land in artifacts/local/browser/explicit-promotion/.
import { DATA, fromBuild, launchBrowser, shotsDir } from "../lib/browser-env.mjs";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { once } from "node:events";
const { loadWorld } = await fromBuild("src/world/loader.js");
const { createOpeningCampaign } = await fromBuild("src/campaign/opening-state.js");
const { GameSession } = await fromBuild("src/app/game-session.js");
const { FileCampaignRepository } = await fromBuild("src/persistence/campaign-repository.js");
const { createPlaytestServer } = await fromBuild("src/ui/server.js");
const world = await loadWorld(DATA);
const LR = "heartstone_lr", M = "calderan_slave_market";
const person = (name, where, status = "active") => ({ kind: "register_character", character: { id: `campaign_character_${name.toLowerCase()}`, origin: { kind: "created" }, profile: { name, age: { kind: "exact", years: 26 } }, current: { current_location: where, status } } });
const c = createOpeningCampaign(world, "browser_rite");
c.apply({ expected_revision: c.revision, commands: [{ kind: "runtime_delta", delta: { player_location: LR } }, person("Brenna", LR), person("Sovela", M), person("Dara", LR, "inactive"), { kind: "register_character", character: { id: "korvin", origin: { kind: "canonical", canonical_entity_id: "korvin" }, profile: {}, current: { status: "active" } } }, { kind: "move_character", character_id: "korvin", location_id: LR }] });
const dir = await mkdtemp(join(tmpdir(), "browser-rite-"));
const repository = new FileCampaignRepository(world, dir); await repository.saveCampaign(c);
const deps = { world, repository, createCoordinator: () => ({ async *runTurn() {} }) };
const loaded = await GameSession.loadCampaign(deps, "browser_rite");
const session = loaded.session;
const server = createPlaytestServer(session); server.listen(0, "127.0.0.1"); await once(server, "listening");
const url = `http://127.0.0.1:${server.address().port}/`;
const SHOTS = await shotsDir("explicit-promotion");
const browser = await launchBrowser();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const results = []; const ok = (name, cond) => { results.push([cond ? "PASS" : "FAIL", name]); console.log(cond ? "PASS" : "FAIL", name); };
let posts = 0; page.on("request", r => { if (r.method() === "POST" && r.url().includes("/api/npc-plus/promote")) posts++; });
await page.goto(url); await page.waitForSelector("#scene-participants button, #scene-participants *");
const open = async name => { await page.locator("#scene-participants >> text=" + name).first().click(); await page.waitForSelector("#character-overlay:not([hidden])"); };
const close = async () => { await page.click("#character-close"); await page.waitForSelector("#character-overlay", { state: "hidden" }); };
const visible = sel => page.locator(sel).isVisible();
console.log(await page.locator("#scene-participants").innerText());
await open("Brenna");
ok("1-2 campaign NPC Brenna: promotion arrow visible", await visible("#character-promote-button"));
ok("   no NPC+ editor controls before promotion", (await page.locator("#character-footer-actions button").count()) === 0);
await page.screenshot({ path: `${SHOTS}/1-arrow.png` });
await page.click("#character-promote-button");
ok("3-4 click opens the confirmation (no request yet)", (await visible("#character-promote-confirm")) && posts === 0);
console.log("   title:", await page.locator("#character-promote-title").innerText());
await page.screenshot({ path: `${SHOTS}/2-confirm.png` });
await page.click("#character-promote-cancel");
ok("5 cancel works (no request, arrow back)", !(await visible("#character-promote-confirm")) && (await visible("#character-promote-button")) && posts === 0);
await page.click("#character-promote-button");
const rev0 = session.getView().session.revision;
await page.click("#character-promote-confirm-button");
await page.waitForFunction(() => document.querySelector("#character-footer-actions button")?.textContent === "Edit NPC+");
ok("6-8 confirm sends exactly one request and Brenna becomes NPC+", posts === 1 && /NPC\+/.test(await page.locator("#character-badges").innerText()));
ok("9 the arrow disappears", !(await visible("#character-promote")));
ok("10 NPC+ editor capabilities available (Generate + Edit NPC+)", (await page.locator("#character-footer-actions button").allInnerTexts()).includes("Edit NPC+") && (await page.locator("#character-portrait-actions button").allInnerTexts()).includes("Generate"));
ok("12 no page reload (single navigation)", page.url() === url);
ok("   one revision committed", session.getView().session.revision === rev0 + 1);
await page.screenshot({ path: `${SHOTS}/3-npcplus.png` });
await close();
await page.click("#household-nav");
await page.waitForSelector("#household-cards");
ok("11 Brenna appears in the Heartstone household", /Brenna/.test(await page.locator("#household-cards").innerText()));
await page.screenshot({ path: `${SHOTS}/4-household.png` });
await page.click("#household-close");
// no control for already NPC+, Player, ineligible
await open("Brenna"); ok("   already NPC+: no arrow", !(await visible("#character-promote"))); await close();
const present = await page.locator("#scene-participants").innerText();
for (const name of ["Korvin"]) { if (present.includes(name)) { await open(name); ok(`   campaign-record canonical ${name} (inside, eligible): arrow visible`, await visible("#character-promote-button")); await close(); } }
await open("Unfamiliar person"); ok("   campaign-record canonical NPC (masked identity): eligible, arrow shows only the masked label", (await visible("#character-promote-button")) && /Unfamiliar person/.test(await page.locator("#character-promote-button").getAttribute("aria-label"))); await page.click("#character-promote-button"); console.log("   masked confirm:", await page.locator("#character-promote-title").innerText()); await close();
// Player entry has no card
const nicco = page.locator("#scene-participants >> text=Nicco").first();
if (await nicco.count()) { await nicco.click({ trial: false }).catch(() => undefined); ok("   Player: no promotion control", !(await visible("#character-promote"))); }
await browser.close(); server.close();
const fails = results.filter(r => r[0] === "FAIL"); console.log(`\n${results.length - fails.length}/${results.length} checks passed`); process.exit(fails.length ? 1 : 0);
